const mongoose = require("mongoose");

// to store the payment details in the database
// creating a new schema for the payment model
const paymentSchema = new mongoose.Schema(
  {
    userId: {
      type: mongoose.Types.ObjectId,
      ref: "User", // each payment is associated with a user,
      // so we are referencing the User model
      required: true,
    },
    paymentId: {
      type: String, // it is optional because it will be generated by Razorpay
      // after the payment is successful
      required: false,
    },
    orderId: {
      type: String,
      unique: true,
      sparse: true,
    },
    status: {
      type: String,
      required: true,
      enum: ["creating", "create_failed", "created", "authorized", "failed", "captured", "partially_refunded", "refunded"],
    },
    amount: {
      type: Number,
      required: true,
    },
    currency: {
      type: String,
      required: true,
    },
    receipt: {
      type: String,
      required: true,
    },
    notes: {
      firstName: {
        type: String,
      },
      lastName: {
        type: String,
      },
      emailId: String,
      membershipType: {
        type: String,
      },
    },
    membershipType: { type: String, enum: ["silver", "gold"], required: true },
    durationMonths: { type: Number, required: true },
    mode: { type: String, enum: ["test", "live"], required: true },
    requestId: { type: String, required: true },
    fulfilledAt: Date,
    membershipExpiresAt: Date,
    amountRefunded: { type: Number, default: 0 },
  },
  { timestamps: true }
);
paymentSchema.index({ userId: 1, requestId: 1 }, { unique: true });
paymentSchema.index({ paymentId: 1 }, { unique: true, sparse: true });

module.exports = mongoose.model("Payment", paymentSchema);
